-- RF-13 / CR-013: tabla de periodos de teletrabajo. PostgreSQL 14+.
-- Contrato propuesto por Jorge en specs/CR-013-registro-teletrabajo.md; lo usan
-- PostgreSqlTeletrabajoRepository (RF-13) y PostgreSqlReporteTeletrabajoRepository (RF-14).
--
-- Contrato:
--   * crea public."Teletrabajo" si no existe; si ya existe y le falta alguna columna del
--     contrato, aborta sin modificar nada;
--   * es idempotente: repetirla no cambia nada ni duplica el índice;
--   * "Modalidad": 'T' (total) o 'P' (parcial);
--   * "DiasRemotos": máscara de días remotos lunes=1, martes=2, miércoles=4, jueves=8, viernes=16;
--     total exige 31 y parcial 1 a 30 (entre uno y cuatro días);
--   * "Estado" true = periodo vigente; no hay anulación en esta versión (ver spec);
--   * sin claves foráneas a public."Empleado" hasta revisar sus datos: el repositorio comprueba la
--     existencia del empleado dentro de la transacción del alta;
--   * no carga datos.
--
-- Hipótesis sin restricción en la BD: que un empleado no tenga periodos vigentes solapados lo garantiza el
-- repositorio con un bloqueo de tabla. Un escritor ajeno podría omitirlo; una restricción de exclusión
-- (EXCLUDE USING gist) exigiría la extensión btree_gist y queda pendiente de decidir.

BEGIN;

SET LOCAL lock_timeout = '15s';
SET LOCAL statement_timeout = '1min';
SELECT pg_advisory_xact_lock(hashtext('RRHH:RF-13:20261112_03'));

DO $preflight$
DECLARE
    faltantes text;
BEGIN
    IF to_regclass('public."Teletrabajo"') IS NOT NULL THEN
        SELECT string_agg(c.nombre, ', ')
        INTO faltantes
        FROM unnest(ARRAY['Id', 'IdEmpleado', 'FechaInicio', 'FechaFin', 'Modalidad',
                          'DiasRemotos', 'Autorizacion', 'Estado', 'FechaRegistro']) AS c(nombre)
        WHERE NOT EXISTS (
            SELECT 1 FROM pg_attribute a
            WHERE a.attrelid = 'public."Teletrabajo"'::regclass
              AND a.attname = c.nombre AND NOT a.attisdropped AND a.attnum > 0);

        IF faltantes IS NOT NULL THEN
            RAISE EXCEPTION 'RF-13: public."Teletrabajo" ya existe pero no cumple el contrato; faltan las columnas: %', faltantes;
        END IF;
    END IF;
END
$preflight$;

CREATE TABLE IF NOT EXISTS public."Teletrabajo" (
    "Id"            integer     GENERATED BY DEFAULT AS IDENTITY,
    "IdEmpleado"    integer     NOT NULL,
    "FechaInicio"   date        NOT NULL,
    "FechaFin"      date        NOT NULL,
    "Modalidad"     character(1) NOT NULL,
    "DiasRemotos"   integer     NOT NULL,
    "Autorizacion"  character varying(200),
    "Estado"        boolean     NOT NULL DEFAULT true,
    "FechaRegistro" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "PK_Teletrabajo" PRIMARY KEY ("Id"),
    CONSTRAINT "CK_Teletrabajo_Rango" CHECK ("FechaInicio" <= "FechaFin"),
    CONSTRAINT "CK_Teletrabajo_Modalidad" CHECK ("Modalidad" IN ('T', 'P')),
    CONSTRAINT "CK_Teletrabajo_DiasRemotos" CHECK (
        ("Modalidad" = 'T' AND "DiasRemotos" = 31)
        OR ("Modalidad" = 'P' AND "DiasRemotos" BETWEEN 1 AND 30))
);

CREATE INDEX IF NOT EXISTS "IX_Teletrabajo_Empleado_Periodo"
    ON public."Teletrabajo" ("IdEmpleado", "FechaInicio", "FechaFin");

COMMENT ON TABLE public."Teletrabajo" IS
    'RF-13: periodos de teletrabajo por empleado. Modalidad T total / P parcial; DiasRemotos es una máscara lunes=1 a viernes=16.';

COMMIT;
